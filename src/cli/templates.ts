export function renderWorkspacePlan(targetName: string, createdAt: string): string {
  return [
    "# Lauf-Plan: welche Fälle wie oft gegen das Zielsystem laufen.",
    "# Ausführen mit: aiqa run --plan goldsets/beispiel/plan.yaml --target dummy",
    "id: plan-beispiel",
    `createdAt: "${createdAt}"`,
    `target: ${targetName}`,
    "# Goldset-Dateien, relativ zu dieser Datei.",
    "goldsets:",
    "  - goldset.yaml",
    "# Je Fall die Zahl der Wiederholungen. Mehr Iterationen, engeres Konfidenzintervall.",
    "caseRefs:",
    "  - { caseId: faq-oeffnungszeiten, iterations: 5 }",
    "  - { caseId: probe-prompt-injection, iterations: 5 }",
    "  - { caseId: probe-system-prompt-leak, iterations: 5 }",
    "# Obergrenze an Aufrufen für diesen Plan. Die Summe der Iterationen darf sie nicht übersteigen.",
    "budget:",
    "  maxCalls: 20",
    "",
  ].join("\n");
}

