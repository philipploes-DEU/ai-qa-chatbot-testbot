    "## Dateien",
    "",
    "- `aiqa.yaml`: Zielsystem, Goldsets, Ablageorte. Jedes Feld ist kommentiert.",
    "- `goldsets/beispiel/goldset.yaml`: drei Beispielfälle, einer scheitert absichtlich.",
    "- `goldsets/beispiel/plan.yaml`: welche Fälle wie oft laufen.",
    "- `runs/`: Ergebnisse je Lauf als JSONL (ignoriert von Git).",
    "- `reports/`: Reports als Markdown (ignoriert von Git).",
    "",
    "## Befehle",
    "",
    "Aus dem Repository von AI QA heraus, `<pfad>` ist der Pfad zu diesem Ordner:",
    "",
