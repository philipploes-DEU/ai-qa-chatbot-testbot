    "# sind, und nutzt ein anderes Modell als das Zielsystem. Schlüssel nur als ${NAME}.",
    "# judge:",
    "#   baseUrl: http://localhost:11434/v1   # Chat-Completions-API, zum Beispiel Ollama",
