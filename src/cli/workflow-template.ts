/**
 * GitHub Actions template for scheduled runs of a workspace (issue #14). Written by
 * `aiqa init --with-schedule` to .github/workflows/aiqa.yml inside the workspace repository.
 * Secrets stay in the workspace repository, never in AI QA.
 */
export function renderWorkflow(planPath: string): string {
  return [
    "# Regelmäßige Läufe von AI QA für diesen Arbeitsbereich. Erzeugt von aiqa init --with-schedule.",
    "#",
    "# Auslöser: nächtlich (schedule), von Hand (workflow_dispatch) und nach einem Deployment",
    "# (repository_dispatch mit event_type aiqa-run, zum Beispiel aus der Deploy-Pipeline des Bots).",
    "# Geheimnisse als Secrets dieses Repositories: AIQA_TARGET_TOKEN (oder USER und PASSWORD),",
    "# AIQA_JUDGE_API_KEY und AIQA_AGENTS_API_KEY (nur mit AIQA_ANALYZE).",
    "# Erreicht der GitHub-Runner das Zielsystem nicht (internes Netz), nutze einen Self-hosted",
    "# Runner (runs-on: self-hosted) oder einen Cron auf einem eigenen Server, siehe README von AI QA.",
    "name: aiqa",
    "",
    "on:",
    "  schedule:",
    '    - cron: "0 3 * * *" # täglich um 03:00 UTC',
    "  workflow_dispatch:",
    "  repository_dispatch:",
    "    types: [aiqa-run]",
    "",
    "permissions:",
    "  contents: write # nur nötig, wenn commit-results unten auf true steht",
    "",
    "env:",
    "  AIQA_VERSION: v0.9.1 # Version von AI QA, die der Lauf nutzt",
    `  AIQA_PLAN: ${planPath}`,
    "  # Auf true setzen, um runs/ und reports/ nach jedem Lauf zu committen. Dann vergleicht",
    "  # aiqa compare mit dem Vorlauf und das Regressions-Gate greift.",
    '  AIQA_COMMIT_RESULTS: "false"',
    "  # Auf true setzen, damit der Analyseagent Hypothesen zu den Fehlschlägen bildet. Kostet",
    "  # Modellaufrufe; die Befunde landen im Artefakt und erscheinen erst nach Bestätigung im Report.",
    '  AIQA_ANALYZE: "false"',
    "",
    "jobs:",
    "  aiqa:",
    "    runs-on: ubuntu-latest",
    "    steps:",
    "      - name: Arbeitsbereich auschecken",
    "        uses: actions/checkout@v7",
    "        with:",
    "          path: workspace",
    "",
    "      - name: AI QA auschecken",
    "        uses: actions/checkout@v7",
    "        with:",
    "          repository: philipploes-DEU/ai-qa-chatbot-testbot",
    "          ref: ${{ env.AIQA_VERSION }}",
    "          path: aiqa",
    "",
    "      - name: pnpm einrichten",
    "        uses: pnpm/action-setup@v6",
    "        with:",
    "          package_json_file: aiqa/package.json",
    "",
    "      - name: Node 22 einrichten",
    "        uses: actions/setup-node@v7",
    "        with:",
    "          node-version: 22",
    "",
    "      - name: AI QA installieren",
    "        working-directory: aiqa",
    "        run: pnpm install --frozen-lockfile",
    "",
    "      - name: Prüfen",
    "        working-directory: aiqa",
    "        run: pnpm aiqa -- -w ../workspace validate",
    "",
    "      - name: Lauf",
    "        working-directory: aiqa",
    "        env:",
    "          AIQA_TARGET_TOKEN: ${{ secrets.AIQA_TARGET_TOKEN }}",
    "          AIQA_TARGET_USER: ${{ secrets.AIQA_TARGET_USER }}",
    "          AIQA_TARGET_PASSWORD: ${{ secrets.AIQA_TARGET_PASSWORD }}",
    "          AIQA_JUDGE_API_KEY: ${{ secrets.AIQA_JUDGE_API_KEY }}",
    "        run: pnpm aiqa -- -w ../workspace run --plan $AIQA_PLAN",
    "",
    "      - name: Report",
    "        if: always()",
    "        working-directory: aiqa",
    "        run: |",
    "          pnpm aiqa -- -w ../workspace report --run latest",
    "          pnpm aiqa -- -w ../workspace report --run latest --format html",
    "          pnpm aiqa -- -w ../workspace report --run latest --format junit",
    "          cat ../workspace/reports/$(ls -t ../workspace/reports | grep -v -- '--' | grep '\\.md$' | head -1) >> $GITHUB_STEP_SUMMARY",
    "",
    "      - name: Analyse der Fehlschläge (optional)",
    "        if: always() && env.AIQA_ANALYZE == 'true'",
    "        working-directory: aiqa",
    "        continue-on-error: true # eine fehlgeschlagene Analyse ändert nichts am Lauf",
    "        env:",
    "          AIQA_JUDGE_API_KEY: ${{ secrets.AIQA_JUDGE_API_KEY }}",
    "          AIQA_AGENTS_API_KEY: ${{ secrets.AIQA_AGENTS_API_KEY }}",
    "        run: pnpm aiqa -- -w ../workspace analyze --run latest",
    "",
    "      - name: Vergleich mit dem Vorlauf",
    "        if: always()",
    "        working-directory: aiqa",
    "        continue-on-error: true # ohne Vorlauf gibt es nichts zu vergleichen",
    "        run: pnpm aiqa -- -w ../workspace compare --base previous --head latest --json ../workspace/reports/vergleich.json",
    "",
    "      - name: Gates",
    "        if: always()",
    "        working-directory: aiqa",
    "        run: pnpm aiqa -- -w ../workspace gate --run latest --base previous",
    "",
    "      - name: Ergebnisse als Artefakt",
    "        if: always()",
    "        uses: actions/upload-artifact@v4",
    "        with:",
    "          name: aiqa-${{ github.run_id }}",
    "          path: |",
    "            workspace/runs",
    "            workspace/reports",
    "          if-no-files-found: warn",
    "",
    "      - name: Ergebnisse committen (optional)",
    "        if: always() && env.AIQA_COMMIT_RESULTS == 'true'",
    "        working-directory: workspace",
    "        run: |",
    '          git config user.name "aiqa"',
    '          git config user.email "aiqa@users.noreply.github.com"',
    "          git add -f runs reports",
    '          git commit -m "chore(aiqa): Lauf $(date -u +%Y-%m-%dT%H:%M:%SZ)" || echo "nichts zu committen"',
    "          git push",
    "",
  ].join("\n");
}
